//! Generates `src/generated/protocol.rs` from the schema bundle that codex itself emits.
//!
//! ```text
//! codex app-server generate-json-schema --out /tmp/schema
//! cargo run -p codex-appserver --bin gen -- /tmp/schema/codex_app_server_protocol.v2.schemas.json
//! ```
//!
//! Only the hand-picked roots below and the definitions they reach are generated.

use serde_json::{Value, json};
use std::collections::{BTreeMap, BTreeSet};

/// The subset of the protocol the client uses.
const ROOTS: &[&str] = &[
    "ThreadStartResponse",
    "ThreadResumeResponse",
    "TurnStartResponse",
    "ThreadStatusChangedNotification",
    "TurnCompletedNotification",
    "HookStartedNotification",
    "HookCompletedNotification",
    "ErrorNotification",
    "ItemCompletedNotification",
];

fn refs(v: &Value, out: &mut Vec<String>) {
    match v {
        Value::Object(m) => {
            if let Some(Value::String(r)) = m.get("$ref") {
                out.push(r.trim_start_matches("#/definitions/").to_owned());
            }
            m.values().for_each(|x| refs(x, out));
        }
        Value::Array(a) => a.iter().for_each(|x| refs(x, out)),
        _ => {}
    }
}

fn main() {
    let path = std::env::args()
        .nth(1)
        .expect("usage: gen <codex_app_server_protocol.v2.schemas.json>");
    let bundle: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    let defs = bundle["definitions"].as_object().expect("definitions");
    let mut todo: Vec<String> = ROOTS.iter().map(|s| (*s).to_owned()).collect();
    let mut seen = BTreeSet::new();
    let mut picked = BTreeMap::new();
    while let Some(name) = todo.pop() {
        if !seen.insert(name.clone()) {
            continue;
        }
        let def = defs.get(&name).unwrap_or_else(|| panic!("{name} is not in the bundle"));
        refs(def, &mut todo);
        picked.insert(name, def.clone());
    }
    let schema = json!({"$schema": "http://json-schema.org/draft-07/schema#", "definitions": picked});
    let mut space = typify::TypeSpace::new(typify::TypeSpaceSettings::default().with_struct_builder(false));
    space.add_root_schema(serde_json::from_value(schema).unwrap()).unwrap();
    let file = syn::parse2::<syn::File>(space.to_stream()).unwrap();
    let header = "// @generated by `cargo run --bin gen` from the codex app-server schema; do not edit.\n\
                  #![allow(clippy::all, clippy::pedantic, dead_code, missing_docs)]\n\n";
    let out = concat!(env!("CARGO_MANIFEST_DIR"), "/src/generated/protocol.rs");
    std::fs::write(out, format!("{header}{}", prettyplease::unparse(&file))).unwrap();
    println!("{} definitions -> {out}", picked.len());
}
